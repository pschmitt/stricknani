#!/usr/bin/env python3
"""Regenerate every derived brand asset from the master SVGs in this folder.

Run `just branding` (it provides resvg and shapely through nix). The masters are:

  icon.svg             full icon, rounded square (web favicon, README)
  icon-square.svg      full icon, full-bleed square (Play, maskable and legacy PNGs)
  icon-foreground.svg  ball and face on transparent (Android adaptive foreground)
  icon-monochrome.svg  single-colour ball with the face cut out (themed icon)
  mascot.svg           the ball cropped to its bounds (web Mascot component)
"""

# ruff: noqa: E501

from __future__ import annotations

import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from shapely import affinity
from shapely.geometry import LineString, Point, Polygon
from shapely.geometry.base import BaseGeometry
from shapely.ops import unary_union

BRANDING = Path(__file__).resolve().parent
ROOT = BRANDING.parent
RES = ROOT / "android/app/src/main/res"
FONT_DIRS = [ROOT / "android/app/src/main/res/font"]

BG = "#ffe2ae"


def resvg(svg: Path, out: Path, width: int, height: int | None = None) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    cmd = ["resvg", "-w", str(width), "-h", str(height or width)]
    for d in FONT_DIRS:
        cmd += ["--use-fonts-dir", str(d)]
    subprocess.run([*cmd, str(svg), str(out)], check=True)


# --- geometry shared by the monochrome and notification vectors ------------------------------


Point2 = tuple[float, float]


def quad(p0: Point2, p1: Point2, p2: Point2, n: int = 24) -> list[Point2]:
    return [
        (
            (1 - t) ** 2 * p0[0] + 2 * (1 - t) * t * p1[0] + t**2 * p2[0],
            (1 - t) ** 2 * p0[1] + 2 * (1 - t) * t * p1[1] + t**2 * p2[1],
        )
        for t in (i / n for i in range(n + 1))
    ]


def silhouette(*, wraps: bool, face_scale: float = 1.0) -> BaseGeometry:
    """Ball (r=27 at 54,54, tilted -8 degrees) with its face and wraps cut out."""
    ball = Point(54, 54).buffer(27, quad_segs=48)
    cuts: list[BaseGeometry] = []
    if wraps:
        for pts in (
            quad((24, 38), (54, 27), (86, 42)),
            quad((22, 70), (56, 88), (88, 64)),
        ):
            cuts.append(LineString(pts).buffer(2, cap_style="round", quad_segs=8))
    cuts.append(Point(45, 51).buffer(3.8 * face_scale, quad_segs=16))
    cuts.append(
        LineString(quad((58, 52), (62, 46), (67, 52))).buffer(
            1.8 * face_scale, cap_style="round", quad_segs=8
        )
    )
    mouth = Polygon(quad((45, 60), (54, 74), (63, 60)))
    cuts.append(mouth.buffer(1.0 * face_scale, join_style="round", quad_segs=8))
    shape = ball.difference(unary_union(cuts))
    return affinity.rotate(shape, -8, origin=(54, 54))


def path_data(geom: BaseGeometry, digits: int = 2) -> str:
    geom = geom.simplify(0.04)
    polys = [geom] if geom.geom_type == "Polygon" else list(geom.geoms)
    parts = []
    for poly in polys:
        for ring in [poly.exterior, *poly.interiors]:
            pts = list(ring.coords)[:-1]
            seg = [f"M{pts[0][0]:.{digits}f},{pts[0][1]:.{digits}f}"]
            seg += [f"L{x:.{digits}f},{y:.{digits}f}" for x, y in pts[1:]]
            parts.append("".join(seg) + "Z")
    return " ".join(parts)


def vector_xml(comment: str, size: int, viewport: int, path: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
    <path
        android:fillColor="#FF000000"
        android:fillType="evenOdd"
        android:pathData="{path}" />
</vector>
"""


def android_vectors() -> None:
    # Same 1.36x as ic_launcher_foreground.xml: the ball fills the visible launcher circle.
    mono = affinity.scale(silhouette(wraps=True), 1.36, 1.36, origin=(54, 54))
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(
        vector_xml(
            "Themed launcher icon (Android 13+): the ball silhouette with the face and wraps cut "
            "out, from branding/icon-monochrome.svg. Generated by branding/build.py. Only alpha "
            "matters, the system applies its own tint.",
            108,
            108,
            path_data(mono),
        )
    )
    # Notification small icon: white-on-transparent flat shape, face only (the wraps would turn
    # into noise at 24dp) and a slightly heavier face so it survives the downscale.
    small = silhouette(wraps=False, face_scale=1.2)
    s = 22 / 54
    small = affinity.scale(small, s, s, origin=(54, 54))
    small = affinity.translate(small, 12 - 54, 12 - 54)
    (RES / "drawable/ic_stat_stricknani.xml").write_text(
        vector_xml(
            "Notification small icon: flat white silhouette of the yarn ball with the wink cut "
            "out (Android masks small icons to their alpha). Generated by branding/build.py.",
            24,
            24,
            path_data(small, 3),
        )
    )


# --- rasters ---------------------------------------------------------------------------------


def round_svg(tmp: Path) -> Path:
    src = (BRANDING / "icon-square.svg").read_text()
    wrapped = src.replace(
        '<rect width="108" height="108" fill="#ffe2ae"/>',
        '<clipPath id="round"><circle cx="54" cy="54" r="54"/></clipPath>'
        '<g clip-path="url(#round)"><rect width="108" height="108" fill="#ffe2ae"/>',
    ).replace("</svg>", "</g></svg>")
    out = tmp / "icon-round.svg"
    out.write_text(wrapped)
    return out


def rasters() -> None:
    icon = BRANDING / "icon.svg"
    square = BRANDING / "icon-square.svg"
    for web in (ROOT / "web/static", ROOT / "rust/static"):
        shutil.copy(icon, web / "favicon.svg")
        resvg(icon, web / "icons/icon-192.png", 192)
        resvg(icon, web / "icons/icon-512.png", 512)
    resvg(square, ROOT / "web/static/icons/icon-maskable-512.png", 512)
    shutil.copy(BRANDING / "mascot.svg", ROOT / "web/static/mascot.svg")

    resvg(square, BRANDING / "playstore/icon-512.png", 512)

    with tempfile.TemporaryDirectory() as t:
        tmp = Path(t)
        round_icon = round_svg(tmp)
        for density, px in (
            ("m", 48),
            ("h", 72),
            ("xh", 96),
            ("xxh", 144),
            ("xxxh", 192),
        ):
            d = RES / f"mipmap-{density}dpi"
            resvg(icon, d / "ic_launcher.png", px)
            resvg(round_icon, d / "ic_launcher_round.png", px)
        feature_graphic(tmp)


def feature_graphic(tmp: Path) -> None:
    mascot = (BRANDING / "mascot.svg").read_text()
    inner = mascot.split("<svg", 1)[1].split(">", 1)[1].rsplit("</svg>", 1)[0]
    svg = f"""<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="500" viewBox="0 0 1024 500">
  <rect width="1024" height="500" fill="#fff6e6"/>
  <circle cx="260" cy="250" r="235" fill="{BG}"/>
  <svg x="85" y="75" width="350" height="350" viewBox="21 21 66 66">{inner}</svg>
  <text x="490" y="232" font-family="Nunito" font-weight="800" font-size="100" fill="#16233f">Stricknani</text>
  <text x="494" y="296" font-family="Nunito" font-weight="500" font-size="23" fill="#5b6784">Knitting projects &amp; yarn stash — self-hosted</text>
</svg>
"""
    src = tmp / "feature-graphic.svg"
    src.write_text(svg)
    resvg(src, BRANDING / "playstore/feature-graphic.png", 1024, 500)


def main() -> int:
    android_vectors()
    rasters()
    return 0


if __name__ == "__main__":
    sys.exit(main())
